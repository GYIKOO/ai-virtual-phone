const assert = require('node:assert/strict');
const fs = require('node:fs');
const read = path => fs.readFileSync(path, 'utf8');
const gradle = read('android-shell/app/build.gradle');
const manifest = read('android-shell/app/src/main/AndroidManifest.xml');
const workflow = read('.github/workflows/android-shell.yml');
assert.ok(gradle.includes('System.getenv("SHELL_TEST_BUILD") == "true"'));
assert.ok(gradle.includes('applicationId testBuild ? "app.floatphone.shell.test" : "app.floatphone.shell"'));
assert.ok(gradle.includes('testBuild ? "floatshell-test" : "floatshell"'));
assert.ok(gradle.includes('testBuild ? "@string/test_app_name" : "@string/app_name"'));
assert.ok(manifest.includes('android:label="${shellAppLabel}"'));
assert.ok(manifest.includes('android:scheme="${shellDeepLinkScheme}"'));
assert.ok(manifest.includes('android:usesCleartextTraffic="false"'));
assert.ok(read('android-shell/app/src/main/java/app/floatphone/shell/MainActivity.kt').includes('DEEP_LINK_SCHEME = BuildConfig.DEEP_LINK_SCHEME'));
assert.ok(read('android-shell/app/src/main/res/values/strings.xml').includes('<string name="test_app_name">Float 测试版</string>'));
assert.ok(workflow.includes("SHELL_TEST_BUILD: ${{ github.ref_name != 'main' }}"));
assert.ok(workflow.includes('TEST_SITE_URL: ${{ inputs.site_url }}'));
assert.ok(workflow.includes('branches: [main]'));
assert.ok(workflow.includes("name: float-shell${{ github.ref_name != 'main' && '-test' || '' }}-release"));
console.log('PASS: test package identity, label, deep link, HTTPS and branch build contracts');
